export type StringKey = keyof typeof en;

const strings = getLocales()[0]?.languageCode === 'zh' ? zh : en;

export const t = (key: StringKey) => strings[key];

/** A string with `{{name}}` placeholders filled in. */
export const tf = (key: StringKey, values: Record<string, string>) =>
  strings[key].replaceAll(/{{(\w+)}}/g, (match, name: string) => values[name] ?? match);
